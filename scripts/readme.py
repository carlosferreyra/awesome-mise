"""Generate the discovery index and recipe pages, or check their freshness."""
import argparse
from pathlib import Path
from checks import ROOT, load_catalog


def render():
    categories = load_catalog()
    contents = "\n".join(f"- [{c['name']}](#{c['slug']})" for c in categories)
    sections = []
    for category in categories:
        lines = [f'<a id="{category["slug"]}"></a>', "", f"## {category['name']}", ""]
        if category["slug"] == "automate-everyday-work":
            lines.insert(0, '<a id="project-environments"></a>\n')
        for entry in sorted(category["entries"], key=lambda e: e["name"].casefold()):
            url = str(Path(entry["config"]).with_name("README.md")) if entry["type"] == "recipe" else entry["url"]
            lines.append(f"- [{entry['name']}]({url}) - {entry['description']}")
        sections.append("\n".join(lines))
    template = (ROOT / "template/README.md").read_text()
    return template.replace("@@CONTENTS@@", contents).replace("@@CATALOG@@", "\n\n".join(sections))


def render_recipes():
    pages = {}
    for category in load_catalog():
        for entry in category["entries"]:
            if entry["type"] != "recipe":
                continue
            config = (ROOT / entry["config"]).read_text().rstrip()
            pages[ROOT / Path(entry["config"]).with_name("README.md")] = "\n".join([
                "<!-- Generated by scripts/readme.py; edit catalog.json or mise.toml. -->",
                f"# {entry['name']}", "", entry["description"], "",
                "## Prerequisites and output", "", entry["notes"], "",
                "## Configuration", "",
                "Copy [mise.toml](mise.toml) into a scratch directory. Inspect the configuration before trusting it if mise asks for trust.",
                "", "```toml", config, "```", "", "## Run", "",
                "Run from the directory containing your copied configuration, after preparing the inputs:",
                "", "```sh", entry["usage"], "```", "",
                f"[Primary mise reference]({entry['url']}) · [All recipes](../README.md) · [Back to the list](../../README.md)", "",
            ])
    return pages


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    pages = {ROOT / "README.md": render(), **render_recipes()}
    for path, result in pages.items():
        if args.check:
            if not path.exists() or path.read_text() != result:
                parser.exit(1, f"{path.relative_to(ROOT)} is stale; run python3 scripts/readme.py\n")
        else:
            path.write_text(result)
    print("Generated pages are current." if args.check else "Generated README and recipe pages.")
