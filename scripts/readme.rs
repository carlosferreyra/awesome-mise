//! Generate the discovery index and recipe pages, or check freshness without rewriting.
mod catalog;
use catalog::{Catalog, Result};
use std::fs;
use std::path::{Path, PathBuf};

fn render(root: &Path, catalog: &Catalog) -> Result<Vec<(PathBuf, String)>> {
    let contents = catalog
        .categories
        .iter()
        .map(|c| format!("- [{}](#{})", c.name, c.slug))
        .collect::<Vec<_>>()
        .join("\n");
    let mut sections = Vec::new();
    let mut recipes = Vec::new();
    for category in &catalog.categories {
        let mut lines = vec![
            format!("<a id=\"{}\"></a>", category.slug),
            String::new(),
            format!("## {}", category.name),
            String::new(),
        ];
        if category.slug == "automate-everyday-work" {
            lines.insert(0, "<a id=\"project-environments\"></a>\n".into());
        }
        let mut entries: Vec<_> = category.entries.iter().collect();
        entries.sort_by_key(|entry| entry.name.to_lowercase());
        for entry in entries {
            let url = if let Some(config) = &entry.config {
                // Use URL separators even when running on Windows.
                format!("{}/README.md", config.rsplit_once('/').unwrap().0)
            } else {
                entry.url.clone()
            };
            lines.push(format!("- [{}]({url}) - {}", entry.name, entry.description));
            if entry.kind == "recipe" {
                let config = entry.config.as_ref().unwrap();
                let text = fs::read_to_string(root.join(config))?;
                let page = vec![
                    "<!-- Generated by scripts/readme.rs; edit catalog.json or mise.toml. -->".into(),
                    format!("# {}", entry.name), String::new(), entry.description.clone(), String::new(),
                    "## Prerequisites and output".into(), String::new(), entry.notes.clone(), String::new(),
                    "## Configuration".into(), String::new(),
                    "Copy [mise.toml](mise.toml) into a scratch directory. Inspect the configuration before trusting it if mise asks for trust.".into(),
                    String::new(), "```toml".into(), text.trim_end().into(), "```".into(), String::new(),
                    "## Run".into(), String::new(),
                    "Run from the directory containing your copied configuration, after preparing the inputs:".into(),
                    String::new(), "```sh".into(), entry.usage.as_ref().unwrap().clone(), "```".into(), String::new(),
                    format!("[Primary mise reference]({}) · [All recipes](../README.md) · [Back to the list](../../README.md)", entry.url), String::new(),
                ].join("\n");
                recipes.push((root.join(config).with_file_name("README.md"), page));
            }
        }
        sections.push(lines.join("\n"));
    }
    let template = fs::read_to_string(root.join("template/README.md"))?;
    let readme = template
        .replace("@@CONTENTS@@", &contents)
        .replace("@@CATALOG@@", &sections.join("\n\n"));
    let mut pages = vec![(root.join("README.md"), readme)];
    pages.extend(recipes);
    Ok(pages)
}

fn update(pages: &[(PathBuf, String)], check: bool) -> Result<()> {
    if check {
        for (path, expected) in pages {
            if fs::read_to_string(path).ok().as_ref() != Some(expected) {
                return Err(format!(
                    "{} is stale; run cargo +nightly -Zscript scripts/readme.rs",
                    path.display()
                )
                .into());
            }
        }
    } else {
        for (path, text) in pages {
            fs::write(path, text)?;
        }
    }
    Ok(())
}

fn run() -> Result<()> {
    let mut check = false;
    for arg in std::env::args().skip(1).filter(|a| a != "--") {
        match arg.as_str() {
            "--check" => check = true,
            "--help" | "-h" => {
                println!("usage: readme [--check]");
                return Ok(());
            }
            _ => return Err(format!("unknown argument: {arg}").into()),
        }
    }
    let root = catalog::repo_root()?;
    let catalog = catalog::load(&root)?;
    update(&render(&root, &catalog)?, check)?;
    println!(
        "{}",
        if check {
            "Generated pages are current."
        } else {
            "Generated README and recipe pages."
        }
    );
    Ok(())
}

fn main() -> std::process::ExitCode {
    match run() {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("error: {error}");
            std::process::ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recipe_pages_embed_exact_config_and_index_links_them() {
        let root = catalog::repo_root().unwrap();
        let pages = render(&root, &catalog::load(&root).unwrap()).unwrap();
        for (path, text) in pages.iter().skip(1) {
            let config = fs::read_to_string(path.with_file_name("mise.toml")).unwrap();
            assert!(text.contains(&format!("```toml\n{}\n```", config.trim_end())));
            assert!(
                pages[0].1.contains(
                    &path
                        .strip_prefix(&root)
                        .unwrap()
                        .to_string_lossy()
                        .replace('\\', "/")
                )
            );
        }
    }

    #[test]
    fn freshness_check_does_not_rewrite_stale_or_missing_pages() {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join("README.md");
        let pages = vec![(path.clone(), "current\n".into())];
        assert!(update(&pages, true).is_err());
        assert!(!path.exists());
        fs::write(&path, "stale\n").unwrap();
        assert!(
            update(&pages, true)
                .unwrap_err()
                .to_string()
                .contains("stale")
        );
        assert_eq!(fs::read_to_string(&path).unwrap(), "stale\n");
        update(&pages, false).unwrap();
        assert!(update(&pages, true).is_ok());
    }
}
